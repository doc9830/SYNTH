/**
 * Лёгкий стеммер русского языка — свой список окончаний, без зависимостей.
 *
 * Зачем: память ищет и склеивает записи по токенам (`src/lib/memory.ts`).
 * Без стемминга «погода» и «погоду» — разные токены, поэтому дубли фактов
 * не схлопывались, а релевантная запись могла не попасть в контекст.
 *
 * Как работает: у слова по очереди отрезаются типовые окончания существительных,
 * прилагательных и глаголов (от длинных к коротким), процесс повторяется, пока
 * что-то отрезалось. Остаток не бывает короче `MIN_STEM` — это защита от
 * склейки разных слов: «кофе» не превращается в «коф», а «годы» — в «год».
 *
 * Чего здесь сознательно нет: словаря исключений, чередований («друг/друзья»),
 * приставок и полного алгоритма Snowball. Это компромисс: пара лишних токенов
 * дешевле, чем склеенный неверный факт (пороги подобраны на тестовом наборе —
 * см. `checks/memory.check.ts`).
 */

/** Минимальная длина основы: короче — уже не слово, а совпадение. */
const MIN_STEM = 4

/** Слово из одной кириллицы: латиницу, цифры и смесь не трогаем. */
const CYRILLIC_WORD_RE = /^[\p{Script=Cyrillic}]+$/u

/**
 * Окончания (существительные, прилагательные, причастия, глаголы).
 * Список намеренно плоский: длинные формы перечислены целиком, короткие
 * односимвольные подчищают остальное на следующем проходе.
 */
const ENDINGS = [
  // прилагательные/причастия в превосходной степени и полные формы
  'ейшими', 'ейший', 'ейшая', 'ейшее', 'ейшие', 'ейшего', 'ейшему', 'ейших', 'ейшим',
  'айшими', 'айший', 'айшая', 'айшее', 'айшие', 'айшего', 'айшему', 'айших', 'айшим',
  'ыми', 'ими', 'ому', 'ему', 'ого', 'его', 'ые', 'ие', 'ым', 'им', 'ой', 'ый', 'ий',
  'ая', 'яя', 'ое', 'ее', 'ую', 'юю', 'ых', 'их', 'ою', 'ею',
  // существительные: множественное число и косвенные падежи
  'иями', 'ями', 'ами', 'иях', 'иям', 'ией', 'ию', 'ия', 'ии', 'ием', 'ий',
  'ах', 'ях', 'ам', 'ям', 'ов', 'ев', 'ей', 'ом', 'ем', 'ью',
  // глаголы: инфинитив, прошедшее время, личные окончания
  'ться', 'тся', 'ился', 'илась', 'илось', 'ились', 'ался', 'алась', 'алось', 'ались',
  'ать', 'ять', 'еть', 'ить', 'ыть', 'уть', 'ешь', 'ишь', 'ете', 'ите', 'ует', 'юет',
  'ет', 'ит', 'ут', 'ют', 'ат', 'ят', 'ал', 'ял', 'ем', 'им',
  // односложные окончания — последний проход
  'а', 'я', 'о', 'е', 'ы', 'и', 'у', 'ю', 'ь',
]

/** Длинные окончания проверяются первыми: иначе «ыми» съест короткое «и». */
const ENDINGS_SORTED = [...new Set(ENDINGS)].sort((a, b) => b.length - a.length)

/**
 * Основа слова: «погода»/«погоду»/«погодой» → «погод», «работает» → «работ».
 * Слова короче `MIN_STEM` + окончание и не-кириллица возвращаются как есть.
 */
export function stemRu(word: string): string {
  // «ё» → «е»: люди пишут и «живёт», и «живет» — это одно и то же слово.
  const lower = word.toLowerCase().replace(/ё/g, 'е').replace(/Ё/g, 'е')
  if (lower.length <= MIN_STEM || !CYRILLIC_WORD_RE.test(lower)) return lower

  let stem = lower
  // Цикл нужен, чтобы «работает» → «работа» → «работ», а не остановиться на «работа»:
  // иначе формы одного слова разъехались бы по разным основам.
  for (let pass = 0; pass < 6; pass += 1) {
    let cut = false
    for (const ending of ENDINGS_SORTED) {
      if (!stem.endsWith(ending)) continue
      if (stem.length - ending.length < MIN_STEM) continue
      stem = stem.slice(0, stem.length - ending.length)
      cut = true
      break
    }
    if (!cut) break
  }
  return stem
}

/** Стемминг списка токенов (дубли основ убираются). */
export function stemTokens(tokens: string[]): string[] {
  return [...new Set(tokens.map(stemRu))]
}
